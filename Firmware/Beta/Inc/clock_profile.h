#ifndef FREEEEG32_CLOCK_PROFILE_H
#define FREEEEG32_CLOCK_PROFILE_H

/* CPU grades keep USB/ADC kernel clocks independent and AHB above USB's 30 MHz
 * minimum. PLL1Q/R stay at 80 MHz. 480 MHz requires silicon rev V; other
 * revisions use 400 MHz instead. Query !INFO for the actual speed/revision.
 */
#ifndef FREEEEG32_CPU_MHZ
#define FREEEEG32_CPU_MHZ 80
#endif

#if FREEEEG32_CPU_MHZ == 40
#define FREEEEG32_CORE_DIVIDER RCC_SYSCLK_DIV2
#define FREEEEG32_AHB_DIVIDER RCC_HCLK_DIV1
#elif FREEEEG32_CPU_MHZ == 80
#define FREEEEG32_CORE_DIVIDER RCC_SYSCLK_DIV1
#define FREEEEG32_AHB_DIVIDER RCC_HCLK_DIV2
#elif FREEEEG32_CPU_MHZ == 160 || FREEEEG32_CPU_MHZ == 240
#define FREEEEG32_CORE_DIVIDER RCC_SYSCLK_DIV1
#define FREEEEG32_AHB_DIVIDER RCC_HCLK_DIV4
#elif FREEEEG32_CPU_MHZ == 320 || FREEEEG32_CPU_MHZ == 400 || FREEEEG32_CPU_MHZ == 480
#define FREEEEG32_CORE_DIVIDER RCC_SYSCLK_DIV1
#define FREEEEG32_AHB_DIVIDER RCC_HCLK_DIV8
#else
#error "Supported FreeEEG32 CPU MHz: 40, 80, 160, 240, 320, 400, 480"
#endif

#if FREEEEG32_CPU_MHZ == 480
#define FREEEEG32_PLL_N (HAL_GetREVID() == REV_ID_V ? 60u : 50u)
#define FREEEEG32_VOLTAGE_SCALE (HAL_GetREVID() == REV_ID_V ? PWR_REGULATOR_VOLTAGE_SCALE0 : PWR_REGULATOR_VOLTAGE_SCALE1)
#else
#define FREEEEG32_PLL_N (FREEEEG32_CPU_MHZ <= 80 ? 10u : FREEEEG32_CPU_MHZ / 8u)
#if FREEEEG32_CPU_MHZ <= 160
#define FREEEEG32_VOLTAGE_SCALE PWR_REGULATOR_VOLTAGE_SCALE3
#elif FREEEEG32_CPU_MHZ == 240
#define FREEEEG32_VOLTAGE_SCALE PWR_REGULATOR_VOLTAGE_SCALE2
#else
#define FREEEEG32_VOLTAGE_SCALE PWR_REGULATOR_VOLTAGE_SCALE1
#endif
#endif

#define FREEEEG32_PLL_QR (FREEEEG32_PLL_N / 5u)
#if FREEEEG32_CPU_MHZ >= 240
#define FREEEEG32_PLL_VCO RCC_PLL1VCOWIDE
#else
#define FREEEEG32_PLL_VCO RCC_PLL1VCOMEDIUM
#endif
/* H7 crystal Y2 (HSE): 16 MHz per the BOM, confirmed on the bench by timing
 * TIM2 against the PC clock. prepare.py writes the same value into HSE_VALUE.
 * The PLL input stays at 16 MHz, as with HSI / 4, so every profile keeps its
 * N/P/Q/R. */
#define FREEEEG32_HSE_HZ 16000000u
#define FREEEEG32_HSE_PLLM (FREEEEG32_HSE_HZ / 16000000u)
#define FREEEEG32_HSE_PLLN FREEEEG32_PLL_N
#define FREEEEG32_HSE_PLLP 2u
#define FREEEEG32_HSE_PLLQR FREEEEG32_PLL_QR

#if FREEEEG32_CPU_MHZ == 240
/* HCLK=60 MHz, VOS2: above the 55 MHz zero-wait-state limit. */
#define FREEEEG32_FLASH_LATENCY FLASH_LATENCY_1
#else
#define FREEEEG32_FLASH_LATENCY FLASH_LATENCY_0
#endif

#endif
